"""Builds the spec's Appendix B (conformance vector index) from vectors/, so the spec never drifts from the suite.
Run from the repo root:
  python3 -I tools/vector_index.py           print the index
  python3 -I tools/vector_index.py --write   replace the index between the vector-index markers in spec/amep-v0.2.md
  python3 -I tools/vector_index.py --check   exit 1 if the spec's index is out of date
"""
import json
import os
import sys
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
VEC = os.path.join(ROOT, "vectors")
SPEC = os.path.join(ROOT, "spec", "amep-v0.2.md")
START, END = "<!-- vector-index:start -->", "<!-- vector-index:end -->"


def build() -> str:
    pos = sorted(f[:-5] for f in os.listdir(os.path.join(VEC, "positive")) if f.endswith(".json"))
    groups = defaultdict(list)
    for f in sorted(os.listdir(os.path.join(VEC, "must-reject"))):
        if f.endswith(".json"):
            e = json.load(open(os.path.join(VEC, "must-reject", f)))["expect"]
            groups[(int(e["invariant"][1:]), e["outcome"])].append(f[:-5])
    total = len(pos) + sum(len(v) for v in groups.values())
    lines = ["*Generated by `tools/vector_index.py`; regenerate it whenever the suite changes.*", "",
             f"Suite: {total} vectors ({len(pos)} positive, {total - len(pos)} must-reject).", "",
             "**Positive (expect `preserved`):** " + ", ".join(f"`{p}`" for p in pos) + ".", "",
             "**Must-reject:**", "", "| Invariant | Outcome | Vectors |", "|---|---|---|"]
    for (inv, outcome), names in sorted(groups.items(), key=lambda kv: (kv[0][0], kv[0][1] != "unresolved")):
        lines.append(f"| I{inv} | {outcome} | " + ", ".join(f"`{n}`" for n in names) + " |")
    return "\n".join(lines)


def main():
    index = build()
    if len(sys.argv) == 1:
        print(index)
        return 0
    text = open(SPEC, encoding="utf-8").read()
    head, _, rest = text.partition(START)
    old, _, tail = rest.partition(END)
    if not rest or not tail and END not in rest:
        print("vector-index markers not found in the spec"); return 1
    new = f"{head}{START}\n{index}\n{END}{tail}"
    if sys.argv[1] == "--check":
        ok = new == text
        print("spec Appendix B is up to date" if ok else "spec Appendix B is OUT OF DATE: run tools/vector_index.py --write")
        return 0 if ok else 1
    if sys.argv[1] == "--write":
        open(SPEC, "w", encoding="utf-8").write(new)
        print("spec Appendix B updated")
        return 0
    print(__doc__); return 2


if __name__ == "__main__":
    sys.exit(main())
