// Compares AMEP's verdicts on a Provared book with the Provared checker's own expected findings, line by line, and
// writes COMPARISON.md. The book and its expected findings are the format's own sample (Apache-2.0, see the fixture's
// NOTICE.md).
//
// Run from the repo root:  node interop/provared/compare.mjs            (rewrite COMPARISON.md)
//                          node interop/provared/compare.mjs --check    (exit 1 if COMPARISON.md is out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { createHash, createPrivateKey } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { evaluate, verdict } from "../../packages/js/src/core.mjs";
import { Key, sigOk } from "../../packages/js/src/node.mjs";
import { importProvaredBook } from "../../packages/conformance/src/profiles/provared.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const FIX = join(HERE, "..", "..", "packages", "conformance", "test", "fixtures", "provared");
const OUT = join(HERE, "COMPARISON.md");

// deterministic TEST keys for the importer, so the comparison is reproducible
const testKey = (kid, roles) => {
  const seed = createHash("sha256").update(`amep-test-vector-key-v1:${kid}`).digest();
  const der = Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]);
  return new Key(kid, roles, createPrivateKey({ key: der, format: "der", type: "pkcs8" }));
};
const keys = { issuer: testKey("importer-issuer", ["issuer", "approver"]), host: testKey("importer-host", ["host"]),
  observer: testKey("importer-observer", ["observer"]) };

export function compare() {
  const book = readFileSync(join(FIX, "office-supplies.jsonl"), "utf8");
  const expected = JSON.parse(readFileSync(join(FIX, "office-supplies.expected.json"), "utf8"));
  const out = importProvaredBook(book, { keys });
  const results = evaluate(out.packet, out.keys, sigOk, [], structuredClone(out.state));
  const byLine = Object.fromEntries(results.map(r => [out.byInvocation[r.id], r]));
  const rows = out.lines.map(l => {
    const theirs = expected.breaches[l.line] ?? [];
    const r = byLine[l.line];
    let relation = "";
    if (r) {
      if (!theirs.length && r.outcome === "preserved") relation = "agree";
      else if (theirs.length && r.outcome === "violated") relation = "agree: both find a breach";
      else if (theirs.length && r.outcome === "unresolved" && l.stub && !out.mapping.actions.includes(l.stub.action))
        relation = "**AMEP gap**: the action is outside the permission, but only the agent recorded it, and AMEP stops at observer independence (I10) instead of treating the agent's own record as an admission";
      else if (theirs.length && r.outcome === "unresolved") relation = "both flag it; AMEP says the evidence cannot decide it";
      else if (!theirs.length && r.outcome === "unresolved") relation = "AMEP is stricter";
      else if (!theirs.length && r.outcome === "violated") relation = "AMEP finds a breach Provared does not";
      else relation = "Provared finds a breach AMEP does not";
    }
    return { line: l.line, role: l.role, stub: l.stub, problems: l.problems, notChecked: l.notChecked, theirs, r, relation };
  });
  return { out, rows, results, packetVerdict: verdict(results), expected };
}

function render({ out, rows, packetVerdict, expected }) {
  const cell = r => (r ? `\`${r.outcome}\` ${r.invariant}${r.blame ? `, blame \`${r.blame}\`` : ""}${r.gaps.length ? `, gap \`${r.gaps.map(g => g.need).join("`, `")}\`` : ""}` : "");
  const what = row => row.stub ? `stub ${row.stub.seq}: \`${row.stub.action}\`, ${row.stub.countersigned ? "countersigned" : "one-sided"}${row.stub.approved ? ", approved" : ""}` : row.role ?? "";
  const lines = [
    "# AMEP verdicts on a Provared book, beside the Provared checker's own findings",
    "",
    "Generated by `node interop/provared/compare.mjs` from the Provared sample book `office-supplies.jsonl` and its expected findings, `office-supplies.expected.json` (provared/provared at `18510e5a`, Apache-2.0; see `packages/conformance/test/fixtures/provared/NOTICE.md`). `--check` fails if this file is out of date.",
    "",
    `Every record was first checked by the Provared format's own rules (envelope, labels, canonical form, both hybrid signatures, the passkey signatures, fingerprints, the chain). Problems found: ${rows.reduce((n, r) => n + r.problems.length, 0)}. Not checked by the profile: ${[...new Set(rows.flatMap(r => r.notChecked))].join("; ") || "nothing"}.`,
    "",
    "| Line | Record | Provared checker | AMEP | Relation |",
    "|---|---|---|---|---|",
    ...rows.map(r => `| ${r.line} | ${what(r)} | ${r.theirs.length ? r.theirs.map(t => `\`${t}\``).join(", ") : (r.stub ? "no breach" : "")} | ${cell(r.r)} | ${r.relation} |`),
    "",
    `**Book:** Provared: within slips \`${expected.summary.withinSlips}\`, first breach at line ${expected.summary.firstBreach}. AMEP packet verdict: ${cell(packetVerdict)}, decided by \`${packetVerdict.id}\` (line ${out.byInvocation[packetVerdict.id]}).`,
    "",
    "## What the import could not express (gaps)",
    "",
    ...out.gaps.map(g => `- **${g.need}.** ${g.detail}`),
  ];
  return lines.join("\n") + "\n";
}

if (fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const text = render(compare());
  if (process.argv.includes("--check")) {
    const ok = readFileSync(OUT, "utf8") === text;
    console.log(ok ? "COMPARISON.md is up to date" : "COMPARISON.md is out of date: run node interop/provared/compare.mjs");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
