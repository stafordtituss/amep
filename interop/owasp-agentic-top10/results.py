"""Generates the "Results of the cited vectors" table in MAPPING.md from the reference verifier, so that every outcome,
invariant, blame and gap the mapping cites is what the verifier actually returns.

Run from the repo root:  python3 interop/owasp-agentic-top10/results.py           (rewrite the table)
                         python3 interop/owasp-agentic-top10/results.py --check   (exit 1 if it is out of date)
"""
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
sys.path.insert(0, os.path.join(ROOT, "packages", "python", "src"))
from amep_protocol.core import evaluate, evaluate_text, verdict  # noqa: E402

MAPPING = os.path.join(os.path.dirname(os.path.abspath(__file__)), "MAPPING.md")
SUITES = {"vectors": "core", "interop/approval-path-attacks": "approval-path",
          "interop/w3c-agent-identity/delegation-continuity": "delegation"}
BEGIN, END = "<!-- results: generated by results.py -->", "<!-- end of results -->"


def index():
    out = {}
    for d, label in SUITES.items():
        keys = json.load(open(os.path.join(ROOT, d, "keys.json")))
        for sub in ("positive", "must-reject"):
            path = os.path.join(ROOT, d, sub)
            for f in sorted(x for x in os.listdir(path) if x.endswith(".json")) if os.path.isdir(path) else []:
                v = json.load(open(os.path.join(path, f)))
                st = v.get("state")
                res = evaluate_text(v["packet_text"], keys, state=st) if "packet_text" in v else evaluate(v["packet"], keys, state=st)
                out.setdefault(f[:-5], []).append((label, verdict(res)))
    return out


def table(text):
    idx = index()
    rows, seen = [], set()
    for line in text.splitlines():
        m = re.match(r"\| \*\*(ASI\d+)", line)
        if not m:
            continue
        vectors_cell = line.split(" | ")[3]   # Risk | establishes | Invariants | Example vectors | Blame | Out of scope
        for name in re.findall(r"`([a-z0-9][a-z0-9-]+)`", vectors_cell):
            if name in seen:
                continue
            if name not in idx:
                raise SystemExit(f"{m.group(1)} cites `{name}`, which is not a vector in any suite")
            seen.add(name)
            for label, r in idx[name]:
                detail = r.blame if r.outcome == "violated" else ", ".join(g["need"] for g in r.gaps) if r.gaps else ""
                rows.append(f"| {m.group(1)} | `{name}` | {label} | {r.outcome} | {r.invariant} | {detail} |")
    head = ["| First cited in | Vector | Suite | Outcome | Invariant | Blame (violated) or gap (unresolved) |",
            "|---|---|---|---|---|---|"]
    return "\n".join([BEGIN, *head, *rows, END])


def main():
    text = open(MAPPING, encoding="utf-8").read()
    new = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: table(text), text, flags=re.S)
    if "--check" in sys.argv:
        ok = new == text
        print("results table is up to date" if ok else "results table is out of date: run results.py")
        return 0 if ok else 1
    open(MAPPING, "w", encoding="utf-8").write(new)
    print("results table rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
